        <h3>✍️ Prompts para creación de videos con IA</h3>

        <h4>🎬 ¿Qué es un prompt para video?</h4>

        <p>
            Es una instrucción detallada donde describes escenas, acciones, estilo y ambiente del video.
        </p>

        <div class="prompt-text">
            "Video educativo de 1 minuto sobre reciclaje para niños con estilo animado y colores vivos"
        </div>

    </div>

    <div class="bloque">

        <h3>🎥 Estructura de un buen prompt</h3>

        <ul>
            <li>Escena</li>
            <li>Ambiente</li>
            <li>Personajes</li>
            <li>Acciones</li>
            <li>Estilo visual</li>
            <li>Audio</li>
        </ul>

        <div class="prompt-text">
            "Ciudad futurista de noche con autos voladores, luces neón y estilo cinematográfico"
        </div>

    </div>

    <div class="bloque">

        <h3>🚀 Ejemplos de prompts</h3>

        <h4>🌿 Naturaleza</h4>
        <div class="prompt-text">
            "Cascada en la selva tropical con aves y sonido de agua"
        </div>

        <h4>🏙️ Ciudad</h4>
        <div class="prompt-text">
            "Ciudad moderna con lluvia y personas caminando con paraguas"
