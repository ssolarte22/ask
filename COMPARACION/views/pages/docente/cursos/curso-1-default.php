<h1 class="titulo-principal">✍️ Tutorial de creación de prompts para IA</h1>

    <p class="descripcion">
        Aprende a escribir instrucciones efectivas para obtener mejores resultados con inteligencia artificial.
    </p>

    <div class="bloque">

        <h3>📘 ¿Qué son los prompts?</h3>

        <ol>
            <li>
                <h4>Definición</h4>

                <p>
                    Un prompt es la instrucción que le das a una IA.
                    Puede ser algo simple como 
                    <strong>"Explícame qué es la fotosíntesis"</strong>
                    o algo más elaborado como 
                    <strong>"Explícame la fotosíntesis como si fueras un profesor de secundaria, usando ejemplos cotidianos y un lenguaje sencillo."</strong>
                </p>

                <p>
                    La diferencia entre ambos es clave: el segundo le da contexto, estilo y objetivo.
                </p>
            </li>

            <li>
                <h4>¿Por qué son importantes los prompts?</h4>

                <p>
                    Los prompts ayudan a guiar a la IA para obtener respuestas más útiles, claras y ajustadas al propósito que necesitas.
                </p>

                <p>Un buen prompt normalmente tiene 4 partes:</p>
            </li>
        </ol>

        <ul>
            <li>
                <strong>Tarea</strong><br>
                Qué quieres que haga la IA.
                Ejemplo:
                <strong>"Escribe un resumen..."</strong>
            </li>

            <li>
                <strong>Contexto</strong><br>
                Para qué o en qué situación.
                Ejemplo:
                <strong>"...de la Segunda Guerra Mundial para un estudiante de 14 años."</strong>
            </li>

            <li>
                <strong>Formato</strong><br>
                Cómo quieres la respuesta.
                Ejemplo:
                <strong>"En forma de lista con viñetas"</strong>
            </li>

            <li>
                <strong>Estilo o tono</strong><br>
                Cómo debe sonar.
                Ejemplo:
                <strong>"Con tono sencillo y educativo"</strong>
            </li>
        </ul>

        <h4>💡 Ejemplo completo</h4>

        <div class="prompt-text">
            "Escribe un resumen de la Segunda Guerra Mundial para un estudiante de 14 años, en forma de lista, con un tono sencillo y fácil de entender."
        </div>

    </div>

    <div class="bloque">

        <h3>📚 Tipos de prompts</h3>

        <h4>🔹 Prompts simples</h4>

        <p>
            Son instrucciones directas y breves. Funcionan bien para tareas rápidas cuando no se necesita mucho detalle.
        </p>

        <div class="prompt-text">
            Dame ideas de negocios
        </div>

        <ul>
            <li>Útiles para respuestas rápidas</li>
            <li>Pueden ser vagos si no hay suficiente contexto</li>
        </ul>

        <hr>

        <h4>🔹 Prompts con contexto</h4>

        <p>
            Añaden información sobre el objetivo, el público o el escenario.
            Esto ayuda a la IA a entregar respuestas más relevantes.
        </p>

        <div class="prompt-text">
            Dame ideas de negocios en Colombia con bajo presupuesto para jóvenes emprendedores
        </div>

        <ul>
            <li>Respuestas más específicas</li>
            <li>Reduce la ambigüedad</li>
        </ul>

        <hr>

        <h4>🔹 Prompts avanzados</h4>

        <p>
            Incluyen rol, formato, estilo y restricciones para un control total sobre la respuesta.
        </p>

        <div class="prompt-text">
            Actúa como un consultor de negocios. Dame 5 ideas de emprendimiento en Colombia con bajo presupuesto. Explica cada una en 3 líneas y menciona el nivel de dificultad.
        </div>

        <ul>
            <li>Resultados mucho más precisos</li>
            <li>Mejor control del formato y estilo</li>
        </ul>

    </div>

    <div class="bloque">

        <h3>🚀 Técnicas para mejorar tus prompts</h3>

        <h4>👨‍🏫 Asignar roles</h4>

        <p>
            Decirle a la IA quién debe ser hace que la respuesta tenga más foco y un tono adecuado.
        </p>

        <ul>
            <li>Actúa como profesor</li>
            <li>Actúa como programador experto</li>
            <li>Actúa como psicólogo</li>
            <li>Actúa como creador de contenido</li>
        </ul>

        <div class="prompt-text">
            Actúa como un nutricionista y crea una dieta semanal saludable para una persona que quiere perder peso.
        </div>

        <hr>

        <h4>📏 Agregar restricciones</h4>

        <p>
            Las restricciones evitan respuestas demasiado largas o genéricas.
        </p>

        <ul>
            <li>en máximo 100 palabras</li>
            <li>sin usar tecnicismos</li>
            <li>solo en español</li>
            <li>con ejemplos reales</li>
            <li>sin introducción, directo al punto</li>
        </ul>

        <div class="prompt-text">
            Explícame qué es blockchain en menos de 100 palabras, sin tecnicismos y con un ejemplo sencillo.
        </div>

        <hr>

        <h4>🔄 Iterar para mejorar</h4>

        <p>
            Los buenos prompts suelen mejorarse en varios pasos:
            prueba, revisa y ajusta.
        </p>

        <ol>
            <li>Primer prompt</li>
            <li>Revisar la respuesta</li>
            <li>Ajustar el prompt</li>
            <li>Repetir</li>
        </ol>

        <div class="prompt-text">
            Explícame marketing digital para emprendedores principiantes con ejemplos de redes sociales.
        </div>

    </div>

    <div class="bloque">

        <h3>⭐ Ejemplo avanzado</h3>

        <div class="prompt-text">
            Actúa como un experto en marketing digital. Explica qué es el embudo de ventas para alguien sin experiencia. Usa un lenguaje sencillo, incluye un ejemplo de una tienda online de ropa y organiza la respuesta en 3 partes: definición, ejemplo y conclusión. Máximo 200 palabras.
        </div>

        <p>Este prompt funciona bien porque contiene:</p>

        <ul>
            <li>rol</li>
            <li>contexto</li>
            <li>formato</li>
            <li>restricción</li>
        </ul>

    </div>

    <div class="bloque">

        <h3>⚠️ Errores comunes</h3>

        <ul>
            <li><strong>Ser demasiado general:</strong> "Háblame de historia".</li>

            <li><strong>No dar contexto:</strong> la IA no sabe para qué lo quieres.</li>

            <li><strong>No definir formato:</strong> la respuesta puede ser larga y desordenada.</li>

            <li><strong>Pedir muchas cosas sin estructura:</strong> "Explícame todo sobre física, química, biología y matemáticas".</li>
        </ul>

        <hr>

        <h3>🏆 Regla de oro</h3>

        <p>Un buen prompt responde estas preguntas:</p>

        <ul>
            <li>¿Qué quiero?</li>
            <li>¿Para quién es?</li>
            <li>¿Cómo lo quiero?</li>
            <li>¿Con qué estilo?</li>
        </ul>

